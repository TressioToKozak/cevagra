"""Server-owned visits, timed stage checkpoints and authoritative replay grading."""
import hashlib
import json
import math
import secrets
import subprocess
import time
from http.cookies import SimpleCookie, CookieError
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCHEMA = '''
CREATE TABLE IF NOT EXISTS public_sessions (token_hash TEXT PRIMARY KEY, id TEXT UNIQUE NOT NULL, created REAL NOT NULL, seen REAL NOT NULL, visible INTEGER NOT NULL, last_write REAL NOT NULL DEFAULT 0, expires REAL NOT NULL);
CREATE TABLE IF NOT EXISTS game_sessions (id TEXT PRIMARY KEY, owner TEXT NOT NULL, created REAL NOT NULL, expires REAL NOT NULL, state TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS request_limits (key TEXT PRIMARY KEY, started REAL NOT NULL, count INTEGER NOT NULL);
'''

class APIError(Exception):
    def __init__(self, status, message):
        self.status, self.message = status, message


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


def limit(db, key, maximum, seconds, now):
    row = db.execute('SELECT started, count FROM request_limits WHERE key=?', (key,)).fetchone()
    if row and now - row[0] < seconds:
        if row[1] >= maximum:
            raise APIError(429, 'Too many requests. Try again later.')
        db.execute('UPDATE request_limits SET count=count+1 WHERE key=?', (key,))
    else:
        db.execute('INSERT OR REPLACE INTO request_limits VALUES (?, ?, 1)', (key, now))


def worker(data):
    try:
        result = subprocess.run(['node', str(ROOT / 'game-verifier.mjs')], input=json.dumps(data), text=True, capture_output=True, timeout=5, check=True)
        return json.loads(result.stdout)
    except subprocess.CalledProcessError:
        raise APIError(400, 'Invalid gameplay trace') from None
    except (OSError, subprocess.TimeoutExpired, ValueError):
        raise APIError(503, 'Gameplay verification unavailable') from None


def cookie_token(handler):
    try:
        value = SimpleCookie(handler.headers.get('Cookie', '')).get('ceva_visit')
        return value.value if value else ''
    except CookieError:
        return ''


def visit(db, handler, now):
    token = cookie_token(handler)
    row = db.execute('SELECT token_hash,id,seen,visible,last_write FROM public_sessions WHERE token_hash=? AND expires>?', (digest(token), now)).fetchone() if token else None
    if not row:
        raise APIError(401, 'A server visit session is required')
    return row


def credit(db, owner, now):
    row = db.execute('SELECT id,seen,visible FROM public_sessions WHERE token_hash=?', (owner,)).fetchone()
    if not row:
        return
    active = db.execute('SELECT state FROM game_sessions WHERE owner=? AND expires>? ORDER BY created DESC LIMIT 1', (owner, now)).fetchone()
    seconds = 0
    if active and row[2] and now-row[1] <= 30:
        state = json.loads(active[0])
        if state.get('active'):
            config = state['plan']['configs'][state['index']]
            seconds = max(0, min(now, state['started']+config['time'])-max(row[1], state['started']))
    db.execute('UPDATE statistics_visits SET play_ms=play_ms+? WHERE id=?', (round(min(seconds, 20)*1000), row[0]))
    db.execute('UPDATE public_sessions SET seen=? WHERE token_hash=?', (now, owner))


def handle(db, handler, route, data):
    now = time.time()
    if not isinstance(data, dict):
        raise APIError(400, 'Expected JSON object')
    ip = handler.client_address[0]  # Never trust arbitrary forwarded client addresses.
    if route == '/api/session':
        if data:
            raise APIError(400, 'Session identifiers are generated by the server')
        try:
            row = visit(db, handler, now)
            return {'session': True}, None
        except APIError:
            pass
        limit(db, 'visit-minute:'+ip, 30, 60, now)
        limit(db, 'visit-hour:'+ip, 120, 3600, now)
        db.execute('DELETE FROM public_sessions WHERE expires<?', (now,))
        db.execute('DELETE FROM game_sessions WHERE expires<?', (now-86400,))
        db.execute('DELETE FROM request_limits WHERE started<?', (now-86400,))
        token, identifier = secrets.token_urlsafe(32), secrets.token_urlsafe(24)
        db.execute('INSERT INTO public_sessions VALUES (?, ?, ?, ?, 1, 0, ?)', (digest(token), identifier, now, now, now+21600))
        db.execute('INSERT INTO statistics_visits VALUES (?, 0)', (identifier,))
        return {'session': True}, handler.make_cookie('ceva_visit', token, 21600, '/api')
    row = visit(db, handler, now)
    owner = row[0]
    if route == '/api/statistics':
        if set(data)-{'visible'} or type(data.get('visible', True)) is not bool:
            raise APIError(400, 'Client visit IDs and play durations are not accepted')
        changed = int(data.get('visible', True)) != row[3]
        if changed:
            limit(db, 'visibility:'+owner, 10, 60, now)
        if now-row[4] < 5 and not changed:
            return {'saved': True, 'throttled': True}, None
        credit(db, owner, now)
        db.execute('UPDATE public_sessions SET visible=?,last_write=? WHERE token_hash=?', (int(data.get('visible', True)), now, owner))
        return {'saved': True}, None
    limit(db, 'game-api:'+owner, 360, 60, now)
    if route == '/api/game/start':
        if set(data)-{'name', 'email'} or not isinstance(data.get('name'), str) or not 1 <= len(data['name'].strip()) <= 100 or not isinstance(data.get('email'), str) or len(data['email']) > 254 or '@' not in data['email']:
            raise APIError(400, 'Valid participant details required')
        limit(db, 'game-start:'+owner, 10, 60, now)
        plan = worker({'op': 'plan', 'seed': secrets.token_urlsafe(32)})
        identifier = secrets.token_urlsafe(24)
        credit(db, owner, now)
        db.execute('UPDATE game_sessions SET expires=? WHERE owner=? AND expires>?', (now, owner, now))
        state = {'plan': plan, 'index': 0, 'active': False, 'name': data['name'].strip(), 'email': data['email'].strip(), 'results': [], 'finished': False}
        db.execute('INSERT INTO game_sessions VALUES (?, ?, ?, ?, ?)', (identifier, owner, now, now+2700, json.dumps(state)))
        return {'id': identifier, **plan}, None
    allowed = {'/api/game/stage': {'gameId', 'id'}, '/api/game/events': {'gameId', 'nonce', 'seq', 'events'}, '/api/game/end': {'gameId', 'nonce'}, '/api/game/finish': {'gameId'}}
    if route not in allowed or set(data)-allowed[route]:
        raise APIError(400, 'Client result fields are not accepted')
    identifier = data.get('gameId')
    game = db.execute('SELECT state,created FROM game_sessions WHERE id=? AND owner=? AND expires>?', (identifier, owner, now)).fetchone() if isinstance(identifier, str) else None
    if not game:
        raise APIError(401, 'Invalid or expired game session')
    state, created = json.loads(game[0]), game[1]
    def save():
        db.execute('UPDATE game_sessions SET state=? WHERE id=?', (json.dumps(state), identifier))
    if route == '/api/game/finish':
        if state['index'] != len(state['plan']['configs']) or state['active']:
            raise APIError(409, 'All stages must be verified first')
        if state['finished']:
            result = db.execute('SELECT payload FROM runs WHERE id=?', (identifier,)).fetchone()
            if not result:
                raise APIError(410, 'Result has been removed')
            return {'run': json.loads(result[0])}, None
        results = state['results']; attempts = sum(r['attempts'] for r in results)
        run = {'id': identifier, 'name': state['name'], 'email': state['email'], 'normalizedName': ' '.join(state['name'].lower().split()), 'score': sum(r['score'] for r in results), 'accuracy': round(sum(r['correct'] for r in results)/attempts*100) if attempts else 0, 'mistakes': sum(r['mistakes'] for r in results), 'minigameScores': {r['id']: r['score'] for r in results}, 'timestamp': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(now)), 'startedAt': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime(created)), 'verification': 'server-v1', 'runSeed': state['plan']['seed']}
        db.execute('INSERT INTO runs VALUES (?, ?)', (identifier, json.dumps(run)))
        db.execute('INSERT OR IGNORE INTO statistics_runs VALUES (?, ?, ?)', (identifier, state['name'], state['email']))
        state['finished'] = True; save()
        return {'run': run}, None
    if state['finished'] or state['index'] >= len(state['plan']['configs']):
        raise APIError(409, 'Game already completed')
    config = state['plan']['configs'][state['index']]
    if route == '/api/game/stage':
        if state['active'] or data.get('id') != config['id']:
            raise APIError(409, 'Invalid stage sequence')
        nonce = secrets.token_urlsafe(24)
        state.update(active=True, started=now, nonce=digest(nonce), seq=0, events=[])
        db.execute('UPDATE public_sessions SET seen=?,visible=1 WHERE token_hash=?', (now, owner))
        save()
        return {'nonce': nonce}, None
    if not state['active'] or not isinstance(data.get('nonce'), str) or not secrets.compare_digest(digest(data['nonce']), state['nonce']):
        raise APIError(409, 'Invalid stage checkpoint')
    elapsed = now-state['started']
    if elapsed > config['time']+10:
        raise APIError(410, 'Stage expired')
    if route == '/api/game/events':
        events = data.get('events'); previous = state['events'][-1]['at'] if state['events'] else 0
        if type(data.get('seq')) is not int or data['seq'] != state['seq']+1 or not isinstance(events, list) or not 1 <= len(events) <= 400 or len(events)+len(state['events']) > 6000:
            raise APIError(400, 'Invalid action checkpoint')
        fields = {'pick': {'type','at','sku'}, 'sort': {'type','at','id','carrier'}, 'miss': {'type','at','id'}, 'place': {'type','at','id','x','y'}, 'load': {'type','at','id','index'}, 'toggle': {'type','at','value'}, 'submit': {'type','at','action'}, 'wrap': {'type','at','dt','y','holding'}}
        if len(json.dumps(state['events']))+len(json.dumps(events)) > 600000:
            raise APIError(400, 'Gameplay trace too large')
        for event in events:
            if not isinstance(event, dict) or not isinstance(event.get('type'), str) or event['type'] not in fields or set(event)-fields[event['type']] or len(json.dumps(event)) > 512:
                raise APIError(400, 'Invalid action format')
            if not isinstance(event, dict) or type(event.get('at')) not in (int,float) or not math.isfinite(event['at']) or not previous <= event['at'] <= min(config['time']*1000+100, elapsed*1000+150):
                raise APIError(400, 'Invalid action timing')
            previous = event['at']
        if elapsed*1000-previous > 2500:
            raise APIError(400, 'Stale gameplay checkpoint')
        state['events'].extend(events); state['seq'] += 1
        nonce = secrets.token_urlsafe(24); state['nonce'] = digest(nonce); save()
        return {'nonce': nonce, 'seq': state['seq']}, None
    if route == '/api/game/end':
        result = worker({'op': 'replay', 'config': config, 'task': state['plan']['tasks'][config['id']], 'events': state['events'], 'elapsed': min(elapsed, config['time'])})
        credit(db, owner, now)
        state['results'].append(result); state['index'] += 1; state['active'] = False; save()
        return {'result': result}, None
    raise APIError(404, 'Not found')
