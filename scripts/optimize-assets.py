"""Build the explicit runtime manifest and WebP derivatives; retain source PNGs.
Run from the repository root with Pillow installed. Never touches mockups.
"""
import re,json
from pathlib import Path
from PIL import Image
from concurrent.futures import ThreadPoolExecutor
stages=['picking','conveyor','barcode','packing','detective','loading','memory','quality','final']
backgrounds=dict(zip(stages,['assets/speed-picking/background-speed-picking.png','assets/backgrounds/02_conveyor_rush.png','assets/barcode-hunt/background/background-barcode-hunt.png','assets/packing-tetris/background-packing-tetris.png',*['assets/backgrounds/'+name+'.png' for name in ['05_wms_detective','06_truck_loading','07_memory_challenge','08_quality_control','09_final_dispatch']]]))
groups={stage:set([backgrounds[stage]]) for stage in stages};common=set()
prefixes=dict(zip(stages,['speed-picking','conveyor-rush','barcode-hunt','packing-tetris','wms-detective','truck_loading','memory_challenge','quality_control','final_dispatch']))
def add(path):
 path=str(path).replace('.webp','.png')
 stage=next((stage for stage,prefix in prefixes.items() if path.startswith('assets/'+prefix+'/')),None)
 if not stage:stage=next((stage for stage,bg in backgrounds.items() if path==bg),None)
 (groups[stage] if stage else common).add(path)
for file in ['styles.css','game.js','minigames.js']:
 text=Path(file).read_text()
 for path in re.findall(r'assets/[\w/.-]+\.(?:png|webp|svg)',text):add(path)
def folder(path,pattern='*.png'):
 for file in Path(path).glob(pattern):add(file)
for path in ['speed-picking/locations','barcode-hunt/boxes','packing-tetris/boxes','conveyor-rush/belt','conveyor-rush/zones','conveyor-rush/carriers','conveyor-rush/states','conveyor-rush/boxes','conveyor-rush/labels','memory_challenge/gifts','quality_control/boxes']:
 folder('assets/'+path)
for name in ['monitor','compare_arrow','info','lock']:add('assets/wms-detective/icons/'+name+'.png')
for name in ['phase_1_2_pill','phase_2_2_pill','selection_card_slot','checkbox_unchecked','checkbox_checked','info_icon']:add('assets/memory_challenge/ui/'+name+'.png')
add('assets/memory_challenge/scene/memory_conveyor_platform.png')
for path in ['scene/01_trailer_interior_7_bays','scene/02_truck_front_marker','scene/03_rear_door_marker','pallets/05_pallet_crate_base','pallets/06_blank_label_overlay','ui/04_pallets_waiting_panel','ui/08_last_delivery_load_first_banner']:add('assets/truck_loading/'+path+'.png')
for path in ['labels/label_base','damage/damage_crush','damage/damage_tear']:add('assets/quality_control/'+path+'.png')
for path in ['panels/01_order_panel','panels/02_packed_shipment_panel','icons/15_icon_order_clipboard_tile','icons/16_icon_shipment_carton_tile','buttons/05_issue_wrong_quantity','buttons/06_issue_wrong_carrier','buttons/07_issue_wrong_sku','buttons/08_issue_missing_serials']:add('assets/final_dispatch/'+path+'.png')
for name in prefixes.values():add('assets/results/icons/'+name.replace('_','-')+'.svg')
for i in [1,2,3]:add(f'assets/leaderboard/medal-{i}.png')
# Only these conveyor images are rendered, not unused scan/guide artwork.
groups['conveyor']={p for p in groups['conveyor'] if ('/states/' not in p or Path(p).name in ['drop-valid.png','drop-valid-check.png','drop-invalid.png']) and ('/belt/' not in p or Path(p).name in ['belt-base.png','belt-front-trim.png']) and ('/labels/' not in p or Path(p).name.startswith('shipping-label-'))}
paths=sorted(common.union(*groups.values()))
assert all(Path(p).is_file() for p in paths),[p for p in paths if not Path(p).is_file()]
def runtime(path):return path if path.endswith('.svg') or '/cursor/' in path else path.replace('.png','.webp')
def convert(path):
 source=Path(path);target=Path(runtime(path));record={'source':path,'runtime':str(target),'before':source.stat().st_size}
 if source!=target:
  image=Image.open(source);record['sourceDimensions']=list(image.size)
  size=1920 if 'background' in path or 'trailer_interior' in path else 640 if '/locations/' in path or '/boxes/' in path else 128 if '/icons/' in path else 1536 if '/panels/' in path or 'conveyor_platform' in path else 1024
  if not target.exists() or target.stat().st_mtime<source.stat().st_mtime:
   image=image.convert('RGBA');image.thumbnail((size,size),Image.Resampling.LANCZOS);image.save(target,'WEBP',quality=88,method=6,exact=True)
  record['runtimeDimensions']=list(Image.open(target).size)
 record['after']=target.stat().st_size
 return record
with ThreadPoolExecutor(max_workers=4) as pool:records=list(pool.map(convert,paths))
manifest='// Generated by scripts/optimize-assets.py. Only runtime assets; no mockups.\n'
manifest+='export const GAMEPLAY_BACKGROUNDS='+json.dumps({s:runtime(p) for s,p in backgrounds.items()},indent=2)+';\n'
manifest+='export const COMMON_ASSETS='+json.dumps(sorted(map(runtime,common)),indent=2)+';\n'
manifest+='export const GAME_ASSETS='+json.dumps({s:sorted(map(runtime,ps)) for s,ps in groups.items()},indent=2)+';\n'
manifest+='export const COMPETITION_ASSETS=[...new Set([...COMMON_ASSETS,...Object.values(GAME_ASSETS).flat()])];\n'
Path('asset-manifest.js').write_text(manifest)
report={'count':len(records),'before':sum(r['before'] for r in records),'after':sum(r['after'] for r in records),'assets':records}
Path('assets/optimization-report.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({k:v for k,v in report.items() if k!='assets'}))
# Runtime code points to derivatives while source PNGs remain available.
for file in ['styles.css','game.js','minigames.js']:
 text=Path(file).read_text()
 if file=='styles.css':text=re.sub(r'assets/[\w/.-]+\.png',lambda m:runtime(m[0]),text)
 else:text=text.replace('.png','.webp')
 Path(file).write_text(text)
